	 CONSTRAINT "CHK_PAYMENT_TARGET" CHECK (
            (payment_type = 'TRANSFER'
                AND beneficiary_id IS NOT NULL
                AND biller_id IS NULL
                AND consumer_reference IS NULL)
            OR
            (payment_type = 'BILL_PAYMENT'
                AND biller_id IS NOT NULL
                AND beneficiary_id IS NULL
                AND consumer_reference IS NOT NULL)
        ) ENABLE, 
	 CONSTRAINT "PK_PAYMENT_ORDERS" PRIMARY KEY ("PAYMENT_ORDER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_PAYMENT_ORDERS_REFERENCE" UNIQUE ("REFERENCE_NUMBER")
