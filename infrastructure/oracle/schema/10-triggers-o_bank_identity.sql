-- Structure only: O_BANK_IDENTITY / TRIGGER
ALTER SESSION SET CURRENT_SCHEMA = O_BANK_IDENTITY;

  CREATE OR REPLACE EDITIONABLE TRIGGER "O_BANK_IDENTITY"."TRG_AUDIT_EVENTS_IMMUTABLE" 
BEFORE UPDATE OR DELETE ON audit_events
BEGIN
    RAISE_APPLICATION_ERROR(
        -20001,
        'Audit events are append-only and cannot be changed.'
    );
END;

/
ALTER TRIGGER "O_BANK_IDENTITY"."TRG_AUDIT_EVENTS_IMMUTABLE" ENABLE;


  CREATE OR REPLACE EDITIONABLE TRIGGER "O_BANK_IDENTITY"."TRG_NOTIFICATION_READ_AT" 
BEFORE UPDATE OF is_read ON notifications
FOR EACH ROW
BEGIN
    IF :NEW.is_read = 'Y' AND :OLD.is_read = 'N' THEN
        :NEW.read_at := SYSTIMESTAMP;
    ELSIF :NEW.is_read = 'N' THEN
        :NEW.read_at := NULL;
    END IF;
END;

/
ALTER TRIGGER "O_BANK_IDENTITY"."TRG_NOTIFICATION_READ_AT" ENABLE;

