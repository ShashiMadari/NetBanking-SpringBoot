ALTER SESSION SET CURRENT_SCHEMA = O_BANK_IDENTITY;

  CREATE TABLE "O_BANK_IDENTITY"."AUDIT_EVENTS" 
   (	"AUDIT_EVENT_ID" NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 284 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"USER_ID" NUMBER(19,0), 
	"ACTION" VARCHAR2(60) NOT NULL ENABLE, 
	"ENTITY_TYPE" VARCHAR2(50), 
	"ENTITY_ID" VARCHAR2(60), 
	"IP_ADDRESS" VARCHAR2(45), 
	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	"REASON" VARCHAR2(500), 
	 CONSTRAINT "PK_AUDIT_EVENTS" PRIMARY KEY ("AUDIT_EVENT_ID")
  USING INDEX  ENABLE
   ) ;


  CREATE TABLE "O_BANK_IDENTITY"."NOTIFICATIONS" 
   (	"NOTIFICATION_ID" NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 284 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"USER_ID" NUMBER(19,0) NOT NULL ENABLE, 
	"CHANNEL" VARCHAR2(15) DEFAULT 'IN_APP' NOT NULL ENABLE, 
	"EVENT_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"MESSAGE" VARCHAR2(500) NOT NULL ENABLE, 
	"IS_READ" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"READ_AT" TIMESTAMP (6), 
	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	 CONSTRAINT "CHK_NOTIFICATIONS_CHANNEL" CHECK (channel IN ('IN_APP', 'EMAIL')) ENABLE, 
	 CONSTRAINT "CHK_NOTIFICATIONS_READ" CHECK (is_read IN ('Y', 'N')) ENABLE, 
	 CONSTRAINT "PK_NOTIFICATIONS" PRIMARY KEY ("NOTIFICATION_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CHK_NOTIFICATIONS_EVENT" CHECK (
        event_type IN (
            'PAYMENT',
            'LOGIN',
            'CARD',
            'LOAN',
            'SECURITY',
            'BILL_PAYMENT',
            'TRANSFER',
            'BENEFICIARY',
            'STATEMENT',
            'EMI_REMINDER'
        )
    ) ENABLE
   ) ;


  CREATE TABLE "O_BANK_IDENTITY"."USERS" 
   (	"USER_ID" NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 62 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"FULL_NAME" VARCHAR2(120) NOT NULL ENABLE, 
	"EMAIL" VARCHAR2(120) NOT NULL ENABLE, 
	"PHONE" VARCHAR2(15), 
	"PASSWORD_HASH" VARCHAR2(255) NOT NULL ENABLE, 
	"ROLE" VARCHAR2(15) DEFAULT 'CUSTOMER' NOT NULL ENABLE, 
	"OTP_HASH" VARCHAR2(255), 
	"OTP_EXPIRY" TIMESTAMP (6), 
	"OTP_PURPOSE" VARCHAR2(20), 
	"FAILED_ATTEMPTS" NUMBER(2,0) DEFAULT 0 NOT NULL ENABLE, 
	"LOCKED_UNTIL" TIMESTAMP (6), 
	"LOGIN_STATUS" VARCHAR2(20) DEFAULT 'LOGGED_OUT' NOT NULL ENABLE, 
	"NET_BANKING_STATUS" VARCHAR2(25) DEFAULT 'NOT_REGISTERED' NOT NULL ENABLE, 
	"STATUS" VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL ENABLE, 
	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	 CONSTRAINT "CHK_USERS_ROLE" CHECK (role IN ('CUSTOMER', 'ADMIN')) ENABLE, 
	 CONSTRAINT "CHK_USERS_STATUS" CHECK (status IN ('ACTIVE', 'LOCKED', 'INACTIVE')) ENABLE, 
	 CONSTRAINT "CHK_USERS_OTP_PURPOSE" CHECK (otp_purpose IS NULL
            OR otp_purpose IN ('LOGIN', 'PASSWORD_RESET')) ENABLE, 
	 CONSTRAINT "CHK_USERS_LOGIN_STATUS" CHECK (login_status IN ('LOGGED_IN', 'LOGGED_OUT')) ENABLE, 
	 CONSTRAINT "CHK_USERS_NET_BANKING_STATUS" CHECK (net_banking_status IN
            ('NOT_REGISTERED', 'PENDING_ACTIVATION', 'ACTIVE', 'LOCKED')) ENABLE, 
	 CONSTRAINT "CHK_USERS_FAILED_ATTEMPTS" CHECK (failed_attempts >= 0) ENABLE, 
	 CONSTRAINT "PK_USERS" PRIMARY KEY ("USER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_USERS_EMAIL" UNIQUE ("EMAIL")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_USERS_PHONE" UNIQUE ("PHONE")
  USING INDEX  ENABLE
   ) ;

