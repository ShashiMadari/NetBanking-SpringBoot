-- Run this only while connected as BANK_INVESTMENT. It owns investment data only.
CREATE TABLE investment_profiles (
  profile_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL UNIQUE, pan_number VARCHAR2(10),
  kyc_status VARCHAR2(20) DEFAULT 'NOT_STARTED' NOT NULL,
  linked_account_id NUMBER(19), demat_number VARCHAR2(20) UNIQUE,
  demat_status VARCHAR2(20) DEFAULT 'NOT_REQUESTED' NOT NULL,
  wallet_balance NUMBER(15,2) DEFAULT 0 NOT NULL,
  demat_otp_hash VARCHAR2(255), demat_otp_expiry TIMESTAMP,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_investment_kyc CHECK (kyc_status IN ('NOT_STARTED','DEMO_VERIFIED','REJECTED')),
  CONSTRAINT chk_investment_demat CHECK (demat_status IN ('NOT_REQUESTED','PENDING_OTP','ACTIVE','REJECTED')),
  CONSTRAINT chk_wallet_balance CHECK (wallet_balance >= 0)
);
CREATE TABLE investment_products (
  product_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_code VARCHAR2(30) NOT NULL UNIQUE, product_name VARCHAR2(150) NOT NULL,
  product_type VARCHAR2(25) NOT NULL, requires_demat CHAR(1) NOT NULL,
  asset_size VARCHAR2(40), risk_level VARCHAR2(15) NOT NULL, past_return_1y NUMBER(7,2),
  lock_in_months NUMBER(4) DEFAULT 0 NOT NULL, tenure_months NUMBER(4),
  minimum_amount NUMBER(15,2) NOT NULL, current_price NUMBER(15,4), annual_rate NUMBER(6,3),
  exchange_name VARCHAR2(10), active CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT chk_product_type CHECK (product_type IN ('EQUITY','ETF','MUTUAL_FUND','FD','RD','PPF','BOND','GOVT_SECURITY')),
  CONSTRAINT chk_product_demat CHECK (requires_demat IN ('Y','N')),
  CONSTRAINT chk_product_active CHECK (active IN ('Y','N'))
);
CREATE TABLE investment_holdings (
  holding_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL, product_id NUMBER(19) NOT NULL, folio_or_demat_ref VARCHAR2(30),
  quantity NUMBER(18,4) NOT NULL, tenure_months NUMBER(4), invested_amount NUMBER(15,2) NOT NULL, average_cost NUMBER(15,4) NOT NULL,
  current_value NUMBER(15,2) NOT NULL, status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL, opened_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_holding_status CHECK (status IN ('ACTIVE','CLOSED','MATURED'))
);
CREATE TABLE investment_orders (
  order_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL, source_account_id NUMBER(19) NOT NULL, product_id NUMBER(19) NOT NULL, holding_id NUMBER(19),
  order_kind VARCHAR2(15) NOT NULL, investment_mode VARCHAR2(15) NOT NULL, amount NUMBER(15,2) NOT NULL,
  quantity NUMBER(18,4), selected_tenure_months NUMBER(4), exchange_name VARCHAR2(10), otp_hash VARCHAR2(255) NOT NULL, otp_expiry TIMESTAMP NOT NULL,
  status VARCHAR2(22) NOT NULL, reference_number VARCHAR2(40) NOT NULL UNIQUE, failure_code VARCHAR2(40),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, authorised_at TIMESTAMP,
  CONSTRAINT chk_order_kind CHECK (order_kind IN ('BUY','REDEEM')),
  CONSTRAINT chk_order_mode CHECK (investment_mode IN ('LUMPSUM','SIP','AUTO_DEBIT')),
  CONSTRAINT chk_order_status CHECK (status IN ('PENDING_OTP','ALLOTTED','SETTLEMENT_PENDING','REDEEMED','FAILED','REJECTED'))
);
CREATE TABLE investment_schedules (
  schedule_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL, source_account_id NUMBER(19) NOT NULL, product_id NUMBER(19) NOT NULL,
  schedule_type VARCHAR2(15) NOT NULL, amount NUMBER(15,2) NOT NULL, debit_day NUMBER(2) NOT NULL,
  next_debit_date DATE NOT NULL, tenure_months NUMBER(4), status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_schedule_type CHECK (schedule_type IN ('SIP','RD','PPF')),
  CONSTRAINT chk_schedule_status CHECK (status IN ('ACTIVE','PAUSED','CANCELLED'))
);
CREATE TABLE trading_wallet_transactions (
  wallet_transaction_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL, profile_id NUMBER(19) NOT NULL, linked_account_id NUMBER(19) NOT NULL, order_id NUMBER(19),
  transaction_type VARCHAR2(15) NOT NULL, amount NUMBER(15,2) NOT NULL, otp_hash VARCHAR2(255), otp_expiry TIMESTAMP,
  status VARCHAR2(20) NOT NULL, reference_number VARCHAR2(40) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, completed_at TIMESTAMP,
  CONSTRAINT chk_wallet_type CHECK (transaction_type IN ('FUND','WITHDRAW','PURCHASE','SALE')),
  CONSTRAINT chk_wallet_amount CHECK (amount > 0),
  CONSTRAINT chk_wallet_status CHECK (status IN ('PENDING_OTP','COMPLETED','FAILED','REJECTED'))
);
CREATE INDEX idx_invest_order_user ON investment_orders(user_id, status);
CREATE INDEX idx_invest_holding_user ON investment_holdings(user_id, status);
CREATE INDEX idx_wallet_transaction_user ON trading_wallet_transactions(user_id, created_at);

